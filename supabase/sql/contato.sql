-- 1. Criação da tabela mensagens_contato baseada nos campos da tela contato.html:
--    - Nome Completo (contato-nome)
--    - E-mail (contato-email)
--    - Telefone / WhatsApp (contato-tel)
--    - Mensagem / Pedido de Orçamento (contato-msg)
CREATE TABLE IF NOT EXISTS public.mensagens_contato (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,                         -- Nome completo do cliente
    email TEXT NOT NULL,                        -- E-mail para retorno
    telefone TEXT NOT NULL,                     -- Telefone / WhatsApp para contato
    mensagem TEXT NOT NULL,                     -- Mensagem / Pedido de orçamento
    status TEXT NOT NULL DEFAULT 'pendente',    -- pendente, em_atendimento, respondida, arquivada
    usuario_id UUID REFERENCES auth.users(id) ON DELETE SET NULL, -- ID do usuário (se estiver logado)
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW() -- Data e horário do envio
);

-- 2. Habilitar Row Level Security (RLS) para proteção contra acessos indevidos
ALTER TABLE public.mensagens_contato ENABLE ROW LEVEL SECURITY;

-- 3. Permissões de inserção para visitantes da web (anon) e usuários logados (authenticated)
GRANT USAGE ON SCHEMA public TO anon, authenticated;
GRANT INSERT ON TABLE public.mensagens_contato TO anon, authenticated;

-- 4. Política de Segurança RLS:
-- Permite que qualquer visitante do site envie mensagens pelo formulário de contato
DROP POLICY IF EXISTS "Permitir envio de mensagens de contato" ON public.mensagens_contato;
CREATE POLICY "Permitir envio de mensagens de contato"
ON public.mensagens_contato
FOR INSERT
TO anon, authenticated
WITH CHECK (true);

-- 5. Política para leitura de mensagens (apenas administradores ou pelo painel do Supabase)
DROP POLICY IF EXISTS "Leitura restrita a administradores" ON public.mensagens_contato;
CREATE POLICY "Leitura restrita a administradores"
ON public.mensagens_contato
FOR SELECT
TO authenticated
USING (
    auth.uid() = usuario_id 
    OR (auth.jwt() ->> 'role') = 'service_role'
);

-- 6. Índices para agilizar a visualização de novas mensagens no painel
CREATE INDEX IF NOT EXISTS idx_mensagens_contato_criado_em 
    ON public.mensagens_contato (criado_em DESC);

CREATE INDEX IF NOT EXISTS idx_mensagens_contato_status 
    ON public.mensagens_contato (status);

