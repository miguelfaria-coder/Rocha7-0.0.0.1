-- 1. Cria a tabela se ela ainda não existir
CREATE TABLE IF NOT EXISTS public.mensagens_contato (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    email TEXT NOT NULL,
    telefone TEXT NOT NULL,
    mensagem TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pendente',
    usuario_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. Garante que todas as colunas existam (evita erro se a tabela já existia antes)
ALTER TABLE public.mensagens_contato ADD COLUMN IF NOT EXISTS nome TEXT;
ALTER TABLE public.mensagens_contato ADD COLUMN IF NOT EXISTS email TEXT;
ALTER TABLE public.mensagens_contato ADD COLUMN IF NOT EXISTS telefone TEXT;
ALTER TABLE public.mensagens_contato ADD COLUMN IF NOT EXISTS mensagem TEXT;
ALTER TABLE public.mensagens_contato ADD COLUMN IF NOT EXISTS status TEXT DEFAULT 'pendente';
ALTER TABLE public.mensagens_contato ADD COLUMN IF NOT EXISTS usuario_id UUID REFERENCES auth.users(id) ON DELETE SET NULL;
ALTER TABLE public.mensagens_contato ADD COLUMN IF NOT EXISTS criado_em TIMESTAMPTZ DEFAULT NOW();

-- 3. Ativar Row Level Security (RLS)
ALTER TABLE public.mensagens_contato ENABLE ROW LEVEL SECURITY;

-- 4. Permissões de acesso à tabela
GRANT USAGE ON SCHEMA public TO anon, authenticated;
GRANT ALL ON TABLE public.mensagens_contato TO anon, authenticated;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated;

-- 5. Política de Inserção (permite qualquer visitante do site enviar mensagens)
DROP POLICY IF EXISTS "Permitir envio de mensagens de contato" ON public.mensagens_contato;
CREATE POLICY "Permitir envio de mensagens de contato"
ON public.mensagens_contato
FOR INSERT
TO anon, authenticated
WITH CHECK (true);

-- 6. Política de Leitura (apenas administradores ou o próprio usuário logado)
DROP POLICY IF EXISTS "Leitura restrita a administradores" ON public.mensagens_contato;
CREATE POLICY "Leitura restrita a administradores"
ON public.mensagens_contato
FOR SELECT
TO authenticated
USING (
    usuario_id = auth.uid() 
    OR (auth.jwt() ->> 'role') = 'service_role'
);

-- 7. Índices para ordenação e busca rápida
CREATE INDEX IF NOT EXISTS idx_mensagens_contato_criado_em 
    ON public.mensagens_contato (criado_em DESC);

CREATE INDEX IF NOT EXISTS idx_mensagens_contato_status 
    ON public.mensagens_contato (status);
