-- Agência Rocha7 | Tabela do formulário de contato
-- Executar no painel do Supabase > SQL Editor > New query.
-- Seguro para reexecução: cria a tabela se ela ainda não existir e recria a política usada pelo formulário.

CREATE TABLE IF NOT EXISTS public.mensagens_contato (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    email TEXT NOT NULL,
    telefone TEXT NOT NULL,
    mensagem TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pendente',
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT mensagens_contato_nome_check
        CHECK (char_length(trim(nome)) BETWEEN 2 AND 150),
    CONSTRAINT mensagens_contato_email_check
        CHECK (
            char_length(trim(email)) BETWEEN 5 AND 254
            AND position('@' IN email) > 1
        ),
    CONSTRAINT mensagens_contato_telefone_check
        CHECK (char_length(trim(telefone)) BETWEEN 8 AND 30),
    CONSTRAINT mensagens_contato_mensagem_check
        CHECK (char_length(trim(mensagem)) BETWEEN 1 AND 10000),
    CONSTRAINT mensagens_contato_status_check
        CHECK (status IN ('pendente', 'em_atendimento', 'respondida', 'arquivada'))
);

-- Visitantes podem enviar dados, mas não consultar/alterar mensagens existentes.
ALTER TABLE public.mensagens_contato ENABLE ROW LEVEL SECURITY;

-- Limpa privilégios anteriores de API na tabela e concede somente o necessário.
REVOKE ALL PRIVILEGES ON TABLE public.mensagens_contato FROM anon, authenticated;
REVOKE INSERT (nome, email, telefone, mensagem)
    ON TABLE public.mensagens_contato FROM anon, authenticated;
GRANT INSERT (nome, email, telefone, mensagem)
    ON TABLE public.mensagens_contato TO anon, authenticated;

-- Remove políticas de versões anteriores desse setup e define uma única política de envio.
DROP POLICY IF EXISTS "Visitantes podem enviar mensagens" ON public.mensagens_contato;
DROP POLICY IF EXISTS "Administradores podem consultar mensagens" ON public.mensagens_contato;

CREATE POLICY "Visitantes podem enviar mensagens"
ON public.mensagens_contato
FOR INSERT
TO anon, authenticated
WITH CHECK (
    char_length(trim(nome)) BETWEEN 2 AND 150
    AND char_length(trim(email)) BETWEEN 5 AND 254
    AND position('@' IN email) > 1
    AND char_length(trim(telefone)) BETWEEN 8 AND 30
    AND char_length(trim(mensagem)) BETWEEN 1 AND 10000
    AND status = 'pendente'
);

-- Índices úteis para ordenar e filtrar mensagens no painel do banco.
CREATE INDEX IF NOT EXISTS idx_mensagens_contato_criado_em
    ON public.mensagens_contato (criado_em DESC);
CREATE INDEX IF NOT EXISTS idx_mensagens_contato_status
    ON public.mensagens_contato (status);
